#!/usr/bin/env node
// Writes ios/Sources/ScruterCMP/Core/Words.swift from the kit's words (protocol/cmp/words/<lang>.json): the sheet's own
// words in every language a banner speaks, embedded in the module. `node ios/scripts/cmp-words.mjs` writes the file;
// `--check` fails when it is out of date (CI).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const dir = join(root, 'protocol/cmp/words');
const out = join(root, 'ios/Sources/ScruterCMP/Core/Words.swift');
const langs = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
const keys = Object.keys(JSON.parse(readFileSync(join(dir, 'fr.json'), 'utf8')));
const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/gi, (_, h) => `\\u{${h}}`);

const records = langs.map((l) => {
  const w = JSON.parse(readFileSync(join(dir, `${l}.json`), 'utf8'));
  for (const k of keys) if (/[\u001e\u001f]/.test(w[k])) throw new Error(`${l}.${k}: separator character`);
  return [l, ...keys.map((k) => w[k])].join('\u001f');
});
// One string literal, read when a language is drawn: far smaller in the app than a literal per word.
const blob = JSON.stringify(records.join('\u001e')).replace(/\\u([0-9a-f]{4})/gi, (_, h) => `\\u{${h}}`);

let swift = `// Generated by ios/scripts/cmp-words.mjs from protocol/cmp/words: do not edit.
// The sheet's own words (« Étape {n} sur {t} », « Suivant », « Certifié par »…), in the ${langs.length} languages a banner speaks.

/// The words of the sheet that are not the banner's own texts.
struct Words {
${keys.map((k) => `    var ${k}: String`).join('\n')}

    init(_ v: [String]) {
${keys.map((k, i) => `        ${k} = v[${i}]`).join('\n')}
    }

    /// French typography on display (\`Typography.frenchSpacing\`): every word but the colon, which has its own spaces.
    @_optimize(size) func french() -> Words {
        let f = Typography.frenchSpacing
        return Words([${keys.map((k) => (k === 'colon' ? k : `f(${k})`)).join(', ')}])
    }

    static let languages = [${langs.map((l) => `"${l}"`).join(', ')}]

    /// The words of \`lang\` (\`fr-BE\` → fr), else English.
    static func of(_ lang: String) -> Words {
        load(String(lang.lowercased().split(separator: "-").first ?? "")) ?? load("en")!
    }

    static func load(_ lang: String) -> Words? {
        for record in blob.split(separator: "\\u{1E}") {
            let v = record.split(separator: "\\u{1F}", omittingEmptySubsequences: false).map(String.init)
            if v.first == lang && v.count == ${keys.length + 1} { return Words(Array(v.dropFirst())) }
        }
        return nil
    }

    private static let blob = ${blob}
}
`;
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== swift) {
    console.error('Words.swift is out of date: node ios/scripts/cmp-words.mjs');
    process.exit(1);
  }
  console.log(`Words.swift: ${langs.length} languages, up to date`);
} else {
  writeFileSync(out, swift);
  console.log(`wrote ${out}`);
}
